// ── the injected crash ──────────────────────────────────────────────────────

/// Fail exactly the next fenced terminal commit. The two flags cut the two
/// halves of the same window: `fail` kills the task terminal after the turn
/// terminal committed; `fail_turn` kills the turn terminal itself, leaving the
/// delivery durable with no `TurnFinished` at all.
struct FailNextFinish {
    inner: Arc<dyn TerminalStore>,
    /// Shared across boots: the test injects the crash on the fixture, and a
    /// fresh runtime over the same database must hit it.
    fail: Arc<AtomicBool>,
    fail_turn: Arc<AtomicBool>,
}

impl FailNextFinish {
    fn new(
        inner: Arc<dyn TerminalStore>,
        fail: Arc<AtomicBool>,
        fail_turn: Arc<AtomicBool>,
    ) -> Self {
        Self {
            inner,
            fail,
            fail_turn,
        }
    }

    fn inject(&self) {
        self.fail.store(true, Ordering::SeqCst);
    }

    fn inject_turn(&self) {
        self.fail_turn.store(true, Ordering::SeqCst);
    }

    fn should_fail(&self) -> bool {
        self.fail.swap(false, Ordering::SeqCst)
    }

    fn should_fail_turn(&self) -> bool {
        self.fail_turn.swap(false, Ordering::SeqCst)
    }
}

#[async_trait]
impl TerminalStore for FailNextFinish {
    async fn finish_task(
        &self,
        session_id: &SessionId,
        event_type: &str,
        payload: &str,
        outcome: TaskOutcome,
        status: SessionStatus,
        state: AgentState,
        now: Timestamp,
    ) -> Result<EventRecord, StorageError> {
        self.inner
            .finish_task(session_id, event_type, payload, outcome, status, state, now)
            .await
    }

    async fn finish_turn(
        &self,
        session_id: &SessionId,
        turn_id: &TurnId,
        event_type: &str,
        payload: &str,
        outcome: TurnOutcome,
        now: Timestamp,
    ) -> Result<EventRecord, StorageError> {
        self.inner
            .finish_turn(session_id, turn_id, event_type, payload, outcome, now)
            .await
    }

    async fn finish_task_owned(
        &self,
        token: &OwnershipToken,
        session_id: &SessionId,
        event_type: &str,
        payload: &str,
        outcome: TaskOutcome,
        status: SessionStatus,
        state: AgentState,
        goal: Option<&GoalTerminalUpdate>,
        now: Timestamp,
    ) -> Result<TaskTerminalCommit, OwnershipError> {
        if self.should_fail() {
            return Err(OwnershipError::Storage(StorageError::InvalidData(
                "injected crash between the final answer and the task terminal".into(),
            )));
        }
        self.inner
            .finish_task_owned(
                token, session_id, event_type, payload, outcome, status, state, goal, now,
            )
            .await
    }

    async fn finish_turn_owned(
        &self,
        token: &OwnershipToken,
        session_id: &SessionId,
        turn_id: &TurnId,
        event_type: &str,
        payload: &str,
        outcome: TurnOutcome,
        now: Timestamp,
    ) -> Result<EventRecord, OwnershipError> {
        if self.should_fail_turn() {
            return Err(OwnershipError::Storage(StorageError::InvalidData(
                "injected crash inside the turn terminal commit".into(),
            )));
        }
        self.inner
            .finish_turn_owned(
                token, session_id, turn_id, event_type, payload, outcome, now,
            )
            .await
    }
}

