/// The installation identity. A process restart keeps its `RuntimeId` and
/// arrives with a new `BootId`; the crashed boot is then provably dead, which
/// is the shape of the production restart.
const RUNTIME_ID: &str = "g11-runtime";

struct Fixture {
    coding: CodingRuntime,
    runtime: Arc<Runtime>,
    db: Database,
    terminal: Arc<FailNextFinish>,
    session: SessionId,
    dir: tempfile::TempDir,
}

async fn fixture(script: Vec<ModelResponse>) -> Fixture {
    let dir = tempfile::tempdir().unwrap();
    let db = Database::connect_in_memory().await.unwrap();
    let record = SessionRecord::new(
        dir.path().to_string_lossy().as_ref(),
        "goal",
        "mock/m",
        leveler_core::now(),
    );
    SessionRepository::new(&db).create(&record).await.unwrap();
    let session = SessionId::new(record.id);
    SessionRepository::new(&db)
        .set_turn_collaboration(&session, "goal", leveler_core::now())
        .await
        .unwrap();

    let runtime = Arc::new(Runtime::new(script));
    let mut stores = EngineStores::from_database(&db);
    let terminal = Arc::new(FailNextFinish::new(
        stores.terminal.clone(),
        Arc::new(AtomicBool::new(false)),
        Arc::new(AtomicBool::new(false)),
    ));
    stores.terminal = terminal.clone();
    let coding = coding_runtime(stores, runtime.clone(), dir.path(), RUNTIME_ID);
    Fixture {
        coding,
        runtime,
        db,
        terminal,
        session,
        dir,
    }
}

/// A fresh boot over the same durable database, with the fixture's crash
/// injection still armed — the shape of the process that restarts after the
/// crash and may itself die at the same cut.
fn fresh_coding(fx: &Fixture) -> CodingRuntime {
    let mut stores = EngineStores::from_database(&fx.db);
    stores.terminal = Arc::new(FailNextFinish::new(
        stores.terminal.clone(),
        fx.terminal.fail.clone(),
        fx.terminal.fail_turn.clone(),
    ));
    coding_runtime(stores, fx.runtime.clone(), fx.dir.path(), RUNTIME_ID)
}

fn coding_runtime(
    stores: EngineStores,
    runtime: Arc<Runtime>,
    root: &std::path::Path,
    runtime_id: &str,
) -> CodingRuntime {
    CodingRuntime {
        engine: leveler_engine::TaskEngine {
            stores,
            runtime_id: leveler_core::RuntimeId::new(runtime_id),
            boot: EngineBoot {
                id: leveler_core::BootId::generate(),
                liveness: Arc::new(leveler_test_support::TestBoots::new()),
            },
        },
        factory: ExecutorFactory {
            tool_discovery: None,
            resource_grants: Arc::new(leveler_storage::MemoryResourceGrantStore::default()),
            runtime,
            registry: Arc::new(registry()),
            tool_context: ToolContext::new(
                Workspace::new(root).unwrap(),
                PermissionProfile::Assisted,
            ),
            model: ModelRef::new("mock", "m"),
            commit_co_author: true,
            overrides: None,
            background_tasks: Arc::new(leveler_execution::BackgroundTaskRegistry::new()),
            permission_rules: leveler_execution::PermissionRuleSet::default(),
            permission_rules_path: None,
            hook_runner: leveler_execution::HookRunner::empty(".".into()),
            steering: None,
            allow_delegation: true,
            allow_host_input: true,
            capabilities: None,
            independent_review: leveler_agent::coding::IndependentReviewPolicy::Off,
        },
        approver: Arc::new(AutoApprove),
        clarifier: Arc::new(AutoClarify),
        task_cancel: Arc::new(AtomicBool::new(false)),
    }
}

fn spec(fx: &Fixture) -> TaskSpec {
    TaskSpec {
        runtime: leveler_agent::coding::RuntimeTaskSpec {
            goal: "implement the counting feature".to_string(),
            kind: ExecutionKind::Direct,
            continuation: leveler_agent::ContinuationPolicy::bounded(6),
            limits: StepLimits::default(),
        },
        coding: leveler_agent::coding::CodingTaskSpec {
            repository: Some(fx.dir.path().into()),
            mode: PermissionProfile::Assisted,
            sandbox: false,
        },
    }
}

// ── observations ────────────────────────────────────────────────────────────

async fn events(fx: &Fixture) -> Vec<EngineEvent> {
    leveler_storage::EventRepository::new(&fx.db)
        .load(&fx.session)
        .await
        .unwrap()
        .iter()
        .map(|row| EngineEvent::from_payload(&row.payload).unwrap())
        .collect()
}

async fn assistant_texts(fx: &Fixture) -> Vec<String> {
    MessageRepository::new(&fx.db)
        .load(&fx.session)
        .await
        .unwrap()
        .iter()
        .filter_map(|payload| serde_json::from_str::<Message>(payload).ok())
        .filter(|message| message.role == Role::Assistant)
        .map(|message| message.text_content())
        .collect()
}

async fn model_requests(fx: &Fixture) -> usize {
    ModelRequestRepository::new(&fx.db)
        .load_for_session(&fx.session)
        .await
        .unwrap()
        .len()
}

async fn goals(fx: &Fixture) -> Vec<leveler_storage::GoalRecord> {
    let stores = EngineStores::from_database(&fx.db);
    let task = stores
        .tasks
        .task_for_session(&fx.session)
        .await
        .unwrap()
        .unwrap();
    stores.goals.for_task(&task).await.unwrap()
}

fn task_terminals(events: &[EngineEvent]) -> usize {
    events
        .iter()
        .filter(|event| matches!(event, EngineEvent::TaskFinished { .. }))
        .count()
}

fn turn_terminals(events: &[EngineEvent]) -> usize {
    events
        .iter()
        .filter(|event| matches!(event, EngineEvent::TurnFinished { .. }))
        .count()
}

// ── tests ───────────────────────────────────────────────────────────────────

/// The declared same-round answer is durable, then the terminal commit dies.
/// A fresh boot must deliver that answer once: no new model request, no second
/// assistant message, exactly one task terminal.
#[tokio::test]
async fn a_crash_between_the_answer_and_the_task_terminal_delivers_it_once() {
    let fx = fixture(vec![declared_answer(), duplicate_delivery()]).await;
    fx.terminal.inject();
    let spec = spec(&fx);

    let first = fx
        .coding
        .run(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await;
    let error = first.expect_err("the injected terminal failure must surface");
    assert!(
        error
            .to_string()
            .contains("task terminal was not committed"),
        "unexpected error: {error}"
    );

    // The exact cut: the answer and its turn are durable; the task is not.
    assert_eq!(model_requests(&fx).await, 1);
    let transcript = assistant_texts(&fx).await;
    assert_eq!(
        transcript.last().map(String::as_str),
        Some(ANSWER),
        "the answer reached the transcript: {transcript:?}"
    );
    let after_crash = events(&fx).await;
    assert!(
        after_crash.iter().any(|event| matches!(
            event,
            EngineEvent::TurnFinished {
                stop: Some(StopReason::Completed),
                ..
            }
        )),
        "the turn terminal must be durable: {after_crash:?}"
    );
    assert_eq!(task_terminals(&after_crash), 0);
    assert_eq!(goals(&fx).await[0].state, GoalState::Running);

    // Recovery: same answer, no regeneration, one terminal.
    let recovered = fresh_coding(&fx);
    let mut observed = Vec::new();
    let report = recovered
        .resume(
            &fx.session,
            &spec,
            &mut |event| observed.push(event),
            CancellationToken::new(),
        )
        .await
        .expect("the uncommitted delivery resumes");

    assert_eq!(report.stop_reason, StopReason::Completed);
    assert_eq!(report.final_text, ANSWER);
    assert_eq!(
        report.model_steps, 1,
        "the completed turn's step count is kept"
    );
    assert_eq!(
        model_requests(&fx).await,
        1,
        "recovery must not ask the model again"
    );
    assert_eq!(
        assistant_texts(&fx).await,
        transcript,
        "the answer is not written a second time"
    );
    let after = events(&fx).await;
    assert_eq!(task_terminals(&after), 1);
    assert_eq!(
        task_terminals(&observed),
        1,
        "the recovered terminal is projected exactly once"
    );
    assert_eq!(goals(&fx).await[0].state, GoalState::Settled);
}

/// The compatibility path has the same cut: the answer comes from the
/// post-settlement delivery round, and the crash still must not lose or
/// duplicate it.
#[tokio::test]
async fn a_crash_after_the_delivery_round_recovers_the_same_answer() {
    let fx = fixture(vec![
        undeclared_settlement(),
        text(ANSWER),
        duplicate_delivery(),
    ])
    .await;
    fx.terminal.inject();
    let spec = spec(&fx);

    fx.coding
        .run(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await
        .expect_err("the injected terminal failure must surface");
    assert_eq!(
        model_requests(&fx).await,
        2,
        "settlement plus delivery round"
    );
    assert_eq!(
        assistant_texts(&fx).await.last().map(String::as_str),
        Some(ANSWER)
    );

    let recovered = fresh_coding(&fx);
    let report = recovered
        .resume(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await
        .expect("the uncommitted delivery resumes");

    assert_eq!(report.final_text, ANSWER);
    assert_eq!(
        model_requests(&fx).await,
        2,
        "the delivery is recovered, not regenerated"
    );
    assert_ne!(report.final_text, DUPLICATE);
    let after = events(&fx).await;
    assert_eq!(task_terminals(&after), 1);
    assert_eq!(goals(&fx).await[0].state, GoalState::Settled);
}

/// The same window, cut one commit earlier: the delivery decision is durable
/// and the turn terminal is not. Recovery must close that turn from the
/// recorded facts and deliver the same answer — no model request, no second
/// assistant message, one turn terminal and one task terminal.
#[tokio::test]
async fn a_crash_inside_the_turn_terminal_delivers_it_once() {
    let fx = fixture(vec![declared_answer(), duplicate_delivery()]).await;
    fx.terminal.inject_turn();
    let spec = spec(&fx);

    let first = fx
        .coding
        .run(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await;
    let error = first.expect_err("the injected turn-terminal failure must surface");
    assert!(
        error
            .to_string()
            .contains("could not commit the turn terminal"),
        "unexpected error: {error}"
    );

    // The exact cut: the answer and the delivery decision are durable; neither
    // the turn nor the task has a terminal.
    assert_eq!(model_requests(&fx).await, 1);
    let transcript = assistant_texts(&fx).await;
    assert_eq!(
        transcript.last().map(String::as_str),
        Some(ANSWER),
        "the answer reached the transcript: {transcript:?}"
    );
    let after_crash = events(&fx).await;
    assert!(
        after_crash
            .iter()
            .any(|event| matches!(event, EngineEvent::DeliveryCommitted { .. })),
        "the delivery decision must be durable: {after_crash:?}"
    );
    assert_eq!(turn_terminals(&after_crash), 0);
    assert_eq!(task_terminals(&after_crash), 0);
    assert_eq!(goals(&fx).await[0].state, GoalState::Running);

    let recovered = fresh_coding(&fx);
    let mut observed = Vec::new();
    let report = recovered
        .resume(
            &fx.session,
            &spec,
            &mut |event| observed.push(event),
            CancellationToken::new(),
        )
        .await
        .expect("the open delivery turn resumes");

    assert_eq!(report.stop_reason, StopReason::Completed);
    assert_eq!(report.final_text, ANSWER);
    assert_eq!(report.model_steps, 1);
    assert_eq!(
        model_requests(&fx).await,
        1,
        "recovery must not ask the model again"
    );
    assert_eq!(
        assistant_texts(&fx).await,
        transcript,
        "the answer is not written a second time"
    );
    let after = events(&fx).await;
    assert_eq!(turn_terminals(&after), 1, "the turn is closed exactly once");
    assert_eq!(task_terminals(&after), 1);
    assert_eq!(task_terminals(&observed), 1);
    assert_eq!(goals(&fx).await[0].state, GoalState::Settled);
}

/// Recovery is itself crash-safe: if the terminal commit dies again, the next
/// boot still finds the same delivery and commits it once.
#[tokio::test]
async fn recovery_survives_a_second_crash_before_the_terminal_commit() {
    let fx = fixture(vec![declared_answer(), duplicate_delivery()]).await;
    fx.terminal.inject();
    let spec = spec(&fx);
    fx.coding
        .run(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await
        .expect_err("first crash");

    let second = fresh_coding(&fx);
    // The recovery attempt hits the same cut: its own terminal commit dies.
    fx.terminal.inject();
    second
        .resume(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await
        .expect_err("the injected second crash surfaces");

    let third = fresh_coding(&fx);
    let report = third
        .resume(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await
        .expect("the delivery is still recoverable");

    assert_eq!(report.final_text, ANSWER);
    assert_eq!(
        model_requests(&fx).await,
        1,
        "two crashes must not buy a model request"
    );
    let after = events(&fx).await;
    assert_eq!(task_terminals(&after), 1);
    assert_eq!(goals(&fx).await[0].state, GoalState::Settled);
}

/// A committed terminal is final: resuming it is refused before any model
/// request, so the delivered answer is never produced again.
#[tokio::test]
async fn resuming_an_already_completed_task_is_refused_without_a_model_call() {
    let fx = fixture(vec![declared_answer(), duplicate_delivery()]).await;
    let spec = spec(&fx);
    fx.coding
        .run(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await
        .expect("the declared delivery completes");
    assert_eq!(model_requests(&fx).await, 1);

    let error = fresh_coding(&fx)
        .resume(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await
        .expect_err("a committed task terminal is not resumable");
    assert!(
        error.to_string().contains("already completed"),
        "unexpected error: {error}"
    );
    assert_eq!(
        model_requests(&fx).await,
        1,
        "a refused resume buys no model call"
    );
    assert_eq!(assistant_texts(&fx).await, vec![ANSWER.to_string()]);
}
