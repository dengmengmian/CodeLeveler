//! G11 crash cut: the model's final answer is durable, the task terminal is not.
//!
//! `finish_from_result` commits the task terminal — the `TaskFinished` event,
//! the session lifecycle columns and the goal settlement — LAST. A crash in
//! the window after the drive published its delivery and before that commit
//! leaves a completed turn with a durable answer and no task terminal. A plain
//! resume would drive the model again and produce a second answer.
//!
//! These tests inject that exact failure at the terminal store, then recover
//! through the real engine, the real SQLite database and the real turn WAL.

