/// The declared same-round answer is durable, then the terminal commit dies.
/// A fresh boot must deliver that answer once: no new model request, no second
/// assistant message, exactly one task terminal.
#[tokio::test]
async fn a_crash_between_the_answer_and_the_task_terminal_delivers_it_once() {
    let fx = fixture(vec![declared_answer(), duplicate_delivery()]).await;
    fx.terminal.inject();
    let spec = spec(&fx);

    let first = fx
        .coding
        .run(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await;
    let error = first.expect_err("the injected terminal failure must surface");
    assert!(
        error
            .to_string()
            .contains("task terminal was not committed"),
        "unexpected error: {error}"
    );

    // The exact cut: the answer and its turn are durable; the task is not.
    assert_eq!(model_requests(&fx).await, 1);
    let transcript = assistant_texts(&fx).await;
    assert_eq!(
        transcript.last().map(String::as_str),
        Some(ANSWER),
        "the answer reached the transcript: {transcript:?}"
    );
    let after_crash = events(&fx).await;
    assert!(
        after_crash.iter().any(|event| matches!(
            event,
            EngineEvent::TurnFinished {
                stop: Some(StopReason::Completed),
                ..
            }
        )),
        "the turn terminal must be durable: {after_crash:?}"
    );
    assert_eq!(task_terminals(&after_crash), 0);
    assert_eq!(goals(&fx).await[0].state, GoalState::Running);

    // Recovery: same answer, no regeneration, one terminal.
    let recovered = fresh_coding(&fx);
    let mut observed = Vec::new();
    let report = recovered
        .resume(
            &fx.session,
            &spec,
            &mut |event| observed.push(event),
            CancellationToken::new(),
        )
        .await
        .expect("the uncommitted delivery resumes");

    assert_eq!(report.stop_reason, StopReason::Completed);
    assert_eq!(report.final_text, ANSWER);
    assert_eq!(
        report.model_steps, 1,
        "the completed turn's step count is kept"
    );
    assert_eq!(
        model_requests(&fx).await,
        1,
        "recovery must not ask the model again"
    );
    assert_eq!(
        assistant_texts(&fx).await,
        transcript,
        "the answer is not written a second time"
    );
    let after = events(&fx).await;
    assert_eq!(task_terminals(&after), 1);
    assert_eq!(
        task_terminals(&observed),
        1,
        "the recovered terminal is projected exactly once"
    );
    let delivery_positions: Vec<_> = observed
        .iter()
        .enumerate()
        .filter_map(|(i, event)| {
            matches!(event, EngineEvent::DeliveryCommitted { text, .. } if text == ANSWER)
                .then_some(i)
        })
        .collect();
    let finished_positions: Vec<_> = observed
        .iter()
        .enumerate()
        .filter_map(|(i, event)| {
            matches!(event, EngineEvent::RunFinished { text } if text == ANSWER).then_some(i)
        })
        .collect();
    assert_eq!(
        delivery_positions.len(),
        1,
        "recovery exposes the existing delivery once"
    );
    assert_eq!(
        finished_positions.len(),
        1,
        "headless recovery publishes the final answer once"
    );
    assert!(delivery_positions[0] < finished_positions[0]);
    assert_eq!(
        after
            .iter()
            .filter(|event| matches!(event, EngineEvent::DeliveryCommitted { .. }))
            .count(),
        1,
        "observer replay must not append a second durable fact"
    );
    assert_eq!(goals(&fx).await[0].state, GoalState::Settled);
}

/// The compatibility path has the same cut: the answer comes from the
/// post-settlement delivery round, and the crash still must not lose or
/// duplicate it.
#[tokio::test]
async fn a_crash_after_the_delivery_round_recovers_the_same_answer() {
    let fx = fixture(vec![
        undeclared_settlement(),
        text(ANSWER),
        duplicate_delivery(),
    ])
    .await;
    fx.terminal.inject();
    let spec = spec(&fx);

    fx.coding
        .run(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await
        .expect_err("the injected terminal failure must surface");
    assert_eq!(
        model_requests(&fx).await,
        2,
        "settlement plus delivery round"
    );
    assert_eq!(
        assistant_texts(&fx).await.last().map(String::as_str),
        Some(ANSWER)
    );

    let recovered = fresh_coding(&fx);
    let report = recovered
        .resume(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await
        .expect("the uncommitted delivery resumes");

    assert_eq!(report.final_text, ANSWER);
    assert_eq!(
        model_requests(&fx).await,
        2,
        "the delivery is recovered, not regenerated"
    );
    assert_ne!(report.final_text, DUPLICATE);
    let after = events(&fx).await;
    assert_eq!(task_terminals(&after), 1);
    assert_eq!(goals(&fx).await[0].state, GoalState::Settled);
}

/// The same window, cut one commit earlier: the delivery decision is durable
/// and the turn terminal is not. Recovery must close that turn from the
/// recorded facts and deliver the same answer — no model request, no second
/// assistant message, one turn terminal and one task terminal.
#[tokio::test]
async fn a_crash_inside_the_turn_terminal_delivers_it_once() {
    let fx = fixture(vec![declared_answer(), duplicate_delivery()]).await;
    fx.terminal.inject_turn();
    let spec = spec(&fx);

    let first = fx
        .coding
        .run(&fx.session, &spec, &mut |_| {}, CancellationToken::new())
        .await;
    let error = first.expect_err("the injected turn-terminal failure must surface");
    assert!(
        error
            .to_string()
            .contains("could not commit the turn terminal"),
        "unexpected error: {error}"
    );

    // The exact cut: the answer and the delivery decision are durable; neither
    // the turn nor the task has a terminal.
    assert_eq!(model_requests(&fx).await, 1);
    let transcript = assistant_texts(&fx).await;
    assert_eq!(
        transcript.last().map(String::as_str),
        Some(ANSWER),
        "the answer reached the transcript: {transcript:?}"
    );
    let after_crash = events(&fx).await;
    assert!(
        after_crash
            .iter()
            .any(|event| matches!(event, EngineEvent::DeliveryCommitted { .. })),
        "the delivery decision must be durable: {after_crash:?}"
    );
    assert_eq!(turn_terminals(&after_crash), 0);
    assert_eq!(task_terminals(&after_crash), 0);
    assert_eq!(goals(&fx).await[0].state, GoalState::Running);

    let recovered = fresh_coding(&fx);
    let mut observed = Vec::new();
    let report = recovered
        .resume(
            &fx.session,
            &spec,
            &mut |event| observed.push(event),
            CancellationToken::new(),
        )
        .await
        .expect("the open delivery turn resumes");

    assert_eq!(report.stop_reason, StopReason::Completed);
    assert_eq!(report.final_text, ANSWER);
    assert_eq!(report.model_steps, 1);
    assert_eq!(
        model_requests(&fx).await,
        1,
        "recovery must not ask the model again"
    );
    assert_eq!(
        assistant_texts(&fx).await,
        transcript,
        "the answer is not written a second time"
    );
    let after = events(&fx).await;
    assert_eq!(turn_terminals(&after), 1, "the turn is closed exactly once");
    assert_eq!(task_terminals(&after), 1);
    assert_eq!(task_terminals(&observed), 1);
    assert_eq!(goals(&fx).await[0].state, GoalState::Settled);

    // The recovered terminal takes its accounting from the durable request
    // ledger, not from in-memory state the crashed boot lost. The fake model
    // reports no usage, so the single call is counted as unmeasured rather
    // than silently folded into a measured zero.
    let usage = observed
        .iter()
        .find_map(|event| match event {
            EngineEvent::TurnFinished { usage, .. } => Some(usage),
            _ => None,
        })
        .expect("the recovery emitted a turn terminal")
        .expect("the recovered terminal consults the request ledger");
    assert_eq!(usage.requests, 1);
    assert_eq!(usage.unmeasured_requests, 1);
}

