//! Append-only event log: every engine event is persisted with a
//! gapless per-session sequence BEFORE it is delivered to observers, so a
//! crashed run can be reconstructed exactly.

use serde::{Deserialize, Serialize};

use leveler_core::{SessionId, Timestamp, TurnId};

use crate::database::{Database, StorageError};

/// The payload format version written for new events. Replay rejects any
/// persisted version greater than this (a newer writer's event an older reader
/// cannot understand) instead of guessing.
pub const EVENT_SCHEMA_VERSION: i64 = 1;

/// A persisted event row.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, sqlx::FromRow)]
pub struct EventRecord {
    /// Primary key, generated by the caller.
    pub id: String,
    /// Owning session. Sequencing is scoped to this value.
    pub session_id: String,
    /// Owning turn, or `None` for session-level events that belong to no turn.
    pub turn_id: Option<String>,
    /// Position in this session's gapless sequence, assigned on append. A gap
    /// means events were lost, which replay treats as corruption.
    pub sequence: i64,
    /// The event's type tag (queryable without parsing the payload).
    pub event_type: String,
    /// The event's JSON payload.
    pub payload: String,
    /// When the event was recorded, as RFC 3339 text. Not used for ordering —
    /// [`Self::sequence`] is authoritative.
    pub created_at: String,
    /// The payload format version (see [`EVENT_SCHEMA_VERSION`]).
    pub schema_version: i64,
}

/// Read/write access to the `events` table.
pub struct EventRepository<'a> {
    db: &'a Database,
}

impl<'a> EventRepository<'a> {
    /// Borrow `db` for the lifetime of this repository handle.
    pub fn new(db: &'a Database) -> Self {
        Self { db }
    }

    /// Append one event, assigning the next per-session sequence atomically.
    /// Returns the persisted record (with its sequence).
    pub async fn append(
        &self,
        session_id: &SessionId,
        turn_id: Option<&TurnId>,
        event_type: &str,
        payload: &str,
        now: Timestamp,
    ) -> Result<EventRecord, StorageError> {
        let id = leveler_core::EventId::generate().into_inner();
        // Structure-aware redaction (R007 F2): scrub string values only, never
        // the serialized document — and refuse loudly BEFORE the INSERT, so a
        // rejected payload can never corrupt the log or consume a sequence.
        let payload = crate::redact_json_payload_for_session(
            &format!("event (type '{event_type}')"),
            payload,
            Some(session_id.as_str()),
        )?;
        // The sequence is assigned inside the INSERT so concurrent appends on
        // one connection pool cannot race a read-then-write; the UNIQUE index on
        // (session_id, sequence) is the backstop that turns any residual race
        // into a loud failure instead of silent reordering.
        sqlx::query(
            "INSERT INTO events \
             (id, session_id, turn_id, sequence, type, payload, created_at, schema_version) \
             SELECT ?1, ?2, ?3, COALESCE(MAX(sequence), 0) + 1, ?4, ?5, ?6, ?7 \
             FROM events WHERE session_id = ?2",
        )
        .bind(&id)
        .bind(session_id.as_str())
        .bind(turn_id.map(|t| t.as_str().to_string()))
        .bind(event_type)
        .bind(&payload)
        .bind(now.to_rfc3339())
        .bind(EVENT_SCHEMA_VERSION)
        .execute(self.db.pool())
        .await?;
        let row = sqlx::query_as::<_, EventRecord>(
            "SELECT id, session_id, turn_id, sequence, type AS event_type, payload, created_at, \
             schema_version FROM events WHERE id = ?1",
        )
        .bind(&id)
        .fetch_one(self.db.pool())
        .await?;
        Ok(row)
    }

    /// Append many events as one transaction, assigning one contiguous
    /// sequence range in the order given.
    ///
    /// Same durability and redaction contract as [`Self::append`]; the
    /// difference is cost. Per-event append pays a `MAX(sequence)` aggregate,
    /// an INSERT and a readback SELECT — two round-trips each. A real
    /// Multi-Agent turn (parent plus three explorer children, all emitting into
    /// one bounded channel) out-produced that drain rate, overflowed the
    /// channel, and the run was cancelled. Here the aggregate and the commit
    /// are paid once for the whole burst, and each record is built from what
    /// was just written instead of read back.
    ///
    /// Every payload is redacted and validated **before** any INSERT, so one
    /// malformed member refuses the whole batch without consuming a sequence
    /// or persisting a sibling.
    pub async fn append_batch(
        &self,
        session_id: &SessionId,
        turn_id: Option<&TurnId>,
        events: &[(&str, &str)],
        now: Timestamp,
    ) -> Result<Vec<EventRecord>, StorageError> {
        if events.is_empty() {
            return Ok(Vec::new());
        }
        let prepared = events
            .iter()
            .map(|(event_type, payload)| {
                let payload = crate::redact_json_payload_for_session(
                    &format!("event (type '{event_type}')"),
                    payload,
                    Some(session_id.as_str()),
                )?;
                Ok((
                    leveler_core::EventId::generate().into_inner(),
                    (*event_type).to_string(),
                    payload,
                ))
            })
            .collect::<Result<Vec<_>, StorageError>>()?;

        let created_at = now.to_rfc3339();
        let turn = turn_id.map(|t| t.as_str().to_string());
        let mut tx = self.db.pool().begin().await?;
        // One aggregate for the whole range. The transaction plus the UNIQUE
        // index on (session_id, sequence) is what makes that safe against a
        // concurrent writer: a racing batch fails loudly rather than
        // interleaving silently.
        let (base,): (i64,) =
            sqlx::query_as("SELECT COALESCE(MAX(sequence), 0) FROM events WHERE session_id = ?1")
                .bind(session_id.as_str())
                .fetch_one(&mut *tx)
                .await?;

        let mut records = Vec::with_capacity(prepared.len());
        for (offset, (id, event_type, payload)) in prepared.into_iter().enumerate() {
            let sequence = base + offset as i64 + 1;
            sqlx::query(
                "INSERT INTO events \
                 (id, session_id, turn_id, sequence, type, payload, created_at, schema_version) \
                 VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8)",
            )
            .bind(&id)
            .bind(session_id.as_str())
            .bind(&turn)
            .bind(sequence)
            .bind(&event_type)
            .bind(&payload)
            .bind(&created_at)
            .bind(EVENT_SCHEMA_VERSION)
            .execute(&mut *tx)
            .await?;
            records.push(EventRecord {
                id,
                session_id: session_id.as_str().to_string(),
                turn_id: turn.clone(),
                sequence,
                event_type,
                payload,
                created_at: created_at.clone(),
                schema_version: EVENT_SCHEMA_VERSION,
            });
        }
        tx.commit().await?;
        Ok(records)
    }

    /// All events of a session in sequence order.
    pub async fn load(&self, session_id: &SessionId) -> Result<Vec<EventRecord>, StorageError> {
        self.load_after(session_id, 0).await
    }

    /// The highest sequence persisted for a session — the resync anchor a
    /// snapshot advertises. `None` when the session has no events yet.
    pub async fn latest_sequence(
        &self,
        session_id: &SessionId,
    ) -> Result<Option<i64>, StorageError> {
        let row: Option<(Option<i64>,)> =
            sqlx::query_as("SELECT MAX(sequence) FROM events WHERE session_id = ?1")
                .bind(session_id.as_str())
                .fetch_optional(self.db.pool())
                .await?;
        Ok(row.and_then(|(seq,)| seq))
    }

    /// Events with `sequence > after`, in sequence order.
    pub async fn load_after(
        &self,
        session_id: &SessionId,
        after: i64,
    ) -> Result<Vec<EventRecord>, StorageError> {
        let rows = sqlx::query_as::<_, EventRecord>(
            "SELECT id, session_id, turn_id, sequence, type AS event_type, payload, created_at, \
             schema_version FROM events WHERE session_id = ?1 AND sequence > ?2 ORDER BY sequence",
        )
        .bind(session_id.as_str())
        .bind(after)
        .fetch_all(self.db.pool())
        .await?;
        Ok(rows)
    }

    /// Inclusive sequence window `[from_seq, to_seq]`.
    pub async fn load_window(
        &self,
        session_id: &SessionId,
        from_seq: i64,
        to_seq: i64,
    ) -> Result<Vec<EventRecord>, StorageError> {
        let rows = sqlx::query_as::<_, EventRecord>(
            "SELECT id, session_id, turn_id, sequence, type AS event_type, payload, created_at, \
             schema_version FROM events \
             WHERE session_id = ?1 AND sequence >= ?2 AND sequence <= ?3 ORDER BY sequence",
        )
        .bind(session_id.as_str())
        .bind(from_seq)
        .bind(to_seq)
        .fetch_all(self.db.pool())
        .await?;
        Ok(rows)
    }

    /// Per-type counts for a session.
    pub async fn count_by_type(
        &self,
        session_id: &SessionId,
    ) -> Result<Vec<(String, i64)>, StorageError> {
        let rows: Vec<(String, i64)> = sqlx::query_as(
            "SELECT type, COUNT(*) FROM events WHERE session_id = ?1 GROUP BY type ORDER BY MIN(sequence)",
        )
        .bind(session_id.as_str())
        .fetch_all(self.db.pool())
        .await?;
        Ok(rows)
    }

    /// Events whose `type` is in `types`, in sequence order.
    ///
    /// Observatory session-wide aggregates use this so a query loads only the
    /// relevant lifecycle rows (e.g. `tool_call_started` / `tool_call_finished`)
    /// instead of the full session log. Not a TUI dump.
    pub async fn load_by_types(
        &self,
        session_id: &SessionId,
        types: &[&str],
    ) -> Result<Vec<EventRecord>, StorageError> {
        if types.is_empty() {
            return Ok(Vec::new());
        }
        let types_json = serde_json::to_string(types)
            .map_err(|e| StorageError::InvalidData(format!("load_by_types type list: {e}")))?;
        let rows = sqlx::query_as::<_, EventRecord>(
            "SELECT id, session_id, turn_id, sequence, type AS event_type, payload, created_at, \
             schema_version FROM events \
             WHERE session_id = ?1 AND type IN (SELECT value FROM json_each(?2)) \
             ORDER BY sequence",
        )
        .bind(session_id.as_str())
        .bind(&types_json)
        .fetch_all(self.db.pool())
        .await?;
        Ok(rows)
    }

    /// The newest event of `event_type`, optionally scoped to one turn — an
    /// indexed single-row lookup so "latest plan/ledger/snapshot" seeding never
    /// scans the whole session log.
    pub async fn load_last_by_type(
        &self,
        session_id: &SessionId,
        event_type: &str,
        turn_id: Option<&leveler_core::TurnId>,
    ) -> Result<Option<EventRecord>, StorageError> {
        let row = sqlx::query_as::<_, EventRecord>(
            "SELECT id, session_id, turn_id, sequence, type AS event_type, payload, created_at, \
             schema_version FROM events \
             WHERE session_id = ?1 AND type = ?2 AND (?3 IS NULL OR turn_id = ?3) \
             ORDER BY sequence DESC LIMIT 1",
        )
        .bind(session_id.as_str())
        .bind(event_type)
        .bind(turn_id.map(|t| t.as_str()))
        .fetch_optional(self.db.pool())
        .await?;
        Ok(row)
    }
}

