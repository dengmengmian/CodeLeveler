    /// R007 F2 accident regression: an assistant narration containing
    /// `secret PASSWORD:"…"` must never persist as malformed JSON. Pre-fix,
    /// the serialized-text scrubber swallowed the JSON string's closing quote
    /// and the structural bytes after it; replay then hard-failed the whole
    /// session ("unreplayable event payload"). If this test is deleted, that
    /// exact R007 corruption can return unnoticed.
    #[tokio::test]
    async fn append_never_persists_malformed_json_when_redacting() {
        let (db, session) = db_with_session().await;
        let repo = EventRepository::new(&db);
        // Byte-exact R007 corrupting shape (narration ends with `PASSWORD:` at
        // the string boundary) + a companion shape carrying a real secret.
        let accident = r#"{"payload":{"text":"Secrets 标签页有 \"Add new\" 按钮。点击添加 secret PASSWORD:"},"type":"assistant_message"}"#;
        let with_secret = r#"{"payload":{"text":"add secret PASSWORD:\"hunter2-secret-value\""},"type":"assistant_message"}"#;
        for payload in [accident, with_secret] {
            let record = repo
                .append(
                    &session,
                    None,
                    "assistant_message",
                    payload,
                    leveler_core::now(),
                )
                .await
                .unwrap();
            let value: serde_json::Value = serde_json::from_str(&record.payload)
                .expect("persisted payload must stay valid JSON");
            assert_eq!(value["type"], "assistant_message");
        }
        assert!(
            !repo.load(&session).await.unwrap()[1]
                .payload
                .contains("hunter2-secret-value"),
            "secret must not persist"
        );
        // The whole log must stay loadable AND parseable — the replay contract.
        for row in repo.load(&session).await.unwrap() {
            serde_json::from_str::<serde_json::Value>(&row.payload)
                .expect("every persisted event must parse");
        }
    }

    /// A payload that is not valid JSON is refused loudly BEFORE any sequence
    /// is assigned — a failed append must never leave a gap (§42).
    #[tokio::test]
    async fn invalid_payload_is_refused_without_consuming_a_sequence() {
        let (db, session) = db_with_session().await;
        let repo = EventRepository::new(&db);
        repo.append(&session, None, "x", r#"{"i":1}"#, leveler_core::now())
            .await
            .unwrap();
        let err = repo
            .append(&session, None, "x", r#"{"truncated":"#, leveler_core::now())
            .await
            .expect_err("malformed payload must be refused");
        assert!(
            matches!(err, StorageError::InvalidData(_)),
            "refusal must be the typed invalid-data error, got: {err:?}"
        );
        let rec = repo
            .append(&session, None, "x", r#"{"i":2}"#, leveler_core::now())
            .await
            .unwrap();
        assert_eq!(rec.sequence, 2, "failed append must not consume a sequence");
        let seqs: Vec<i64> = repo
            .load(&session)
            .await
            .unwrap()
            .iter()
            .map(|e| e.sequence)
            .collect();
        assert_eq!(seqs, vec![1, 2], "gapless after a refused append");
    }

    /// R007 F6 accident regression, durable-echo half: once a value has been
    /// identified as a secret for this session, it must not re-enter durable
    /// storage even when it arrives as ordinary prose with no key/value shape
    /// left for the structural pass to recognise.
    #[tokio::test]
    async fn registered_session_secret_is_scrubbed_from_assistant_prose() {
        let (db, session) = db_with_session().await;
        let secret = "hunter2-durable-echo-unique";
        leveler_core::clear_session_secrets(session.as_str());
        leveler_core::register_session_secrets(
            session.as_str(),
            &[leveler_core::DetectedSecret {
                value: secret.to_string(),
                key: "API_PASSWORD".to_string(),
            }],
        );

        let payload = serde_json::json!({
            "type": "assistant_message",
            "payload": {"text": format!("The API password is {secret}, noted.")}
        })
        .to_string();
        let record = EventRepository::new(&db)
            .append(
                &session,
                None,
                "assistant_message",
                &payload,
                leveler_core::now(),
            )
            .await
            .unwrap();

        assert!(
            !record.payload.contains(secret),
            "prose echo of a known secret must not persist: {}",
            record.payload
        );
        // The sentence around it survives, and the row is still valid JSON.
        let value: serde_json::Value = serde_json::from_str(&record.payload).unwrap();
        assert!(
            value["payload"]["text"]
                .as_str()
                .unwrap()
                .contains("The API password is"),
            "{record:?}"
        );
        leveler_core::clear_session_secrets(session.as_str());
    }

    /// A secret registered for one session must not be scrubbed out of a
    /// different session's rows — the registry is session-scoped.
    #[tokio::test]
    async fn registered_secrets_do_not_cross_sessions() {
        let (db, session_a) = db_with_session().await;
        let record = SessionRecord::new("/repo", "other", "mock/m", leveler_core::now());
        SessionRepository::new(&db).create(&record).await.unwrap();
        let session_b = SessionId::new(record.id);

        let secret = "alpha-cross-session-value";
        leveler_core::clear_session_secrets(session_a.as_str());
        leveler_core::clear_session_secrets(session_b.as_str());
        leveler_core::register_session_secrets(
            session_a.as_str(),
            &[leveler_core::DetectedSecret {
                value: secret.to_string(),
                key: "TOKEN".to_string(),
            }],
        );

        let payload =
            serde_json::json!({"type": "diagnostic", "payload": {"text": secret}}).to_string();
        let repo = EventRepository::new(&db);
        let in_a = repo
            .append(
                &session_a,
                None,
                "diagnostic",
                &payload,
                leveler_core::now(),
            )
            .await
            .unwrap();
        let in_b = repo
            .append(
                &session_b,
                None,
                "diagnostic",
                &payload,
                leveler_core::now(),
            )
            .await
            .unwrap();

        assert!(!in_a.payload.contains(secret), "own session must scrub");
        assert!(
            in_b.payload.contains(secret),
            "another session must be unaffected: {}",
            in_b.payload
        );
        leveler_core::clear_session_secrets(session_a.as_str());
        leveler_core::clear_session_secrets(session_b.as_str());
    }

