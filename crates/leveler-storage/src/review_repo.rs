//! Durable manual reviews.
//!
//! One row per review execution. The row is independent of turns, goals and
//! task terminals: it has its own id, its own report and its own object
//! identity. Typed payloads stay JSON here because their shape belongs to the
//! review service; the columns exist for history ordering and status filtering
//! without parsing a report.

use leveler_core::{SessionId, Timestamp};

use crate::database::{Database, StorageError};

/// A review being admitted. `status` is the initial lifecycle value the
/// service chose (normally `running`).
pub struct NewReview<'a> {
    /// Stable review id, generated by the caller.
    pub id: &'a str,
    /// The source session this review belongs to.
    pub session_id: &'a SessionId,
    /// The user's review focus, verbatim.
    pub focus: &'a str,
    /// Typed review scope as JSON.
    pub scope_json: &'a str,
    /// The model that will perform the review.
    pub model: &'a str,
    /// Initial lifecycle value (`running`).
    pub status: &'a str,
    /// The reviewed object's owning session (may differ from `session_id`).
    pub source_session_id: Option<&'a str>,
    /// The session turn whose delivery the review is based on, when there is
    /// one. Belongs to `source_session_id`, not necessarily `session_id`.
    pub source_turn_id: Option<&'a str>,
    /// Admission time.
    pub created_at: Timestamp,
}

/// The terminal facts of one review. Every field is written atomically with
/// `status`, so a reader can never see a settled status with a stale report.
pub struct ReviewFinish<'a> {
    /// Final lifecycle value.
    pub status: &'a str,
    /// Concrete object identity captured by the service, as JSON.
    pub object_json: Option<&'a str>,
    /// The review ledger's findings, as JSON.
    pub findings_json: &'a str,
    /// The reviewer's final report, verbatim.
    pub report: &'a str,
    /// Why the review failed, when it did.
    pub error: Option<&'a str>,
    /// Why a non-completed review stopped (budget, cancellation, abnormal
    /// stop). Separate from `error`.
    pub stop_detail: Option<&'a str>,
    /// Model spend attributed to this review, as JSON.
    pub usage_json: &'a str,
    /// Structured coverage, limitations and conclusion, as JSON. `None` means
    /// the reviewer declared nothing.
    pub verdict_json: Option<&'a str>,
    /// Bounded tool-activity trace, as JSON. Diagnostic evidence about the
    /// investigation, never part of the report or the finding ledger.
    pub activity_json: &'a str,
    /// Whether the object moved while the review ran.
    pub object_changed: bool,
    /// Whether the read-only reviewer changed product files (a contract
    /// violation, recorded rather than hidden).
    pub modified_source: bool,
    /// Settlement time.
    pub finished_at: Timestamp,
}

/// One stored review, with its typed payloads still as JSON text.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReviewRecord {
    /// Stable review id.
    pub id: String,
    /// The source session.
    pub session_id: SessionId,
    /// The user's review focus, verbatim.
    pub focus: String,
    /// Typed review scope as JSON.
    pub scope_json: String,
    /// The model that performed the review.
    pub model: String,
    /// Lifecycle value (`running`, `completed`, `incomplete`, `cancelled`,
    /// `failed`).
    pub status: String,
    /// The reviewed object's owning session (may differ from `session_id`).
    pub source_session_id: Option<String>,
    /// The delivery turn in `source_session_id` the review is based on.
    pub source_turn_id: Option<String>,
    /// Concrete object identity as JSON.
    pub object_json: Option<String>,
    /// Findings as JSON.
    pub findings_json: String,
    /// The reviewer's final report, verbatim.
    pub report: String,
    /// Why the review failed, when it did.
    pub error: Option<String>,
    /// Why a non-completed review stopped.
    pub stop_detail: Option<String>,
    /// Model spend as JSON.
    pub usage_json: String,
    /// Structured coverage, limitations and conclusion, as JSON.
    pub verdict_json: Option<String>,
    /// Bounded tool-activity trace, as JSON.
    pub activity_json: String,
    /// Whether the object moved while the review ran.
    pub object_changed: bool,
    /// Whether the reviewer changed product files.
    pub modified_source: bool,
    /// Admission time, RFC 3339.
    pub created_at: String,
    /// Settlement time, RFC 3339.
    pub finished_at: Option<String>,
}

/// Read/write access to the `reviews` table.
pub struct ReviewRepository<'a> {
    db: &'a Database,
}

impl<'a> ReviewRepository<'a> {
    /// Borrow `db` for this repository handle.
    pub fn new(db: &'a Database) -> Self {
        Self { db }
    }

    /// Admit one review row. The caller generated the id; a duplicate is a
    /// storage error rather than a silently reused identity.
    pub async fn create(&self, review: &NewReview<'_>) -> Result<(), StorageError> {
        sqlx::query(
            "INSERT INTO reviews \
             (id, session_id, focus, scope_json, model, status, source_session_id, \
              source_turn_id, findings_json, report, usage_json, created_at) \
             VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8, '[]', '', '{}', ?9)",
        )
        .bind(review.id)
        .bind(review.session_id.as_str())
        .bind(review.focus)
        .bind(review.scope_json)
        .bind(review.model)
        .bind(review.status)
        .bind(review.source_session_id)
        .bind(review.source_turn_id)
        .bind(review.created_at.to_rfc3339())
        .execute(self.db.pool())
        .await?;
        Ok(())
    }

    /// Settle one review from `running` to its terminal.
    ///
    /// The `status = 'running'` guard makes the first terminal writer win:
    /// a settlement racing a stale-row check cannot overwrite a report that
    /// already settled. Returns `false` when no running row with this id
    /// exists (already settled, or gone).
    pub async fn finish(&self, id: &str, finish: &ReviewFinish<'_>) -> Result<bool, StorageError> {
        let result = sqlx::query(
            "UPDATE reviews SET status = ?2, object_json = ?3, findings_json = ?4, \
             report = ?5, error = ?6, stop_detail = ?7, usage_json = ?8, \
             verdict_json = ?9, object_changed = ?10, modified_source = ?11, \
             finished_at = ?12, activity_json = ?13 \
             WHERE id = ?1 AND status = 'running'",
        )
        .bind(id)
        .bind(finish.status)
        .bind(finish.object_json)
        .bind(finish.findings_json)
        .bind(finish.report)
        .bind(finish.error)
        .bind(finish.stop_detail)
        .bind(finish.usage_json)
        .bind(finish.verdict_json)
        .bind(finish.object_changed)
        .bind(finish.modified_source)
        .bind(finish.finished_at.to_rfc3339())
        .bind(finish.activity_json)
        .execute(self.db.pool())
        .await?;
        Ok(result.rows_affected() > 0)
    }

    /// One review by its stable id.
    pub async fn get(&self, id: &str) -> Result<Option<ReviewRecord>, StorageError> {
        let row = sqlx::query(
            "SELECT id, session_id, focus, scope_json, model, status, source_session_id, \
             source_turn_id, object_json, findings_json, report, error, stop_detail, \
             usage_json, verdict_json, object_changed, modified_source, created_at, \
             finished_at, activity_json \
             FROM reviews WHERE id = ?1",
        )
        .bind(id)
        .fetch_optional(self.db.pool())
        .await?;
        row.map(|row| decode_row(&row)).transpose()
    }

    /// Every review of one session, newest first.
    pub async fn list_for_session(
        &self,
        session_id: &SessionId,
    ) -> Result<Vec<ReviewRecord>, StorageError> {
        let rows = sqlx::query(
            "SELECT id, session_id, focus, scope_json, model, status, source_session_id, \
             source_turn_id, object_json, findings_json, report, error, stop_detail, \
             usage_json, verdict_json, object_changed, modified_source, created_at, \
             finished_at, activity_json \
             FROM reviews WHERE session_id = ?1 ORDER BY created_at DESC, id DESC",
        )
        .bind(session_id.as_str())
        .fetch_all(self.db.pool())
        .await?;
        rows.iter().map(decode_row).collect()
    }
}

fn decode_row(row: &sqlx::sqlite::SqliteRow) -> Result<ReviewRecord, StorageError> {
    use sqlx::Row;
    Ok(ReviewRecord {
        id: row.try_get("id")?,
        session_id: SessionId::new(row.try_get::<String, _>("session_id")?),
        focus: row.try_get("focus")?,
        scope_json: row.try_get("scope_json")?,
        model: row.try_get("model")?,
        status: row.try_get("status")?,
        source_session_id: row.try_get("source_session_id")?,
        source_turn_id: row.try_get("source_turn_id")?,
        object_json: row.try_get("object_json")?,
        findings_json: row.try_get("findings_json")?,
        report: row.try_get("report")?,
        error: row.try_get("error")?,
        stop_detail: row.try_get("stop_detail")?,
        usage_json: row.try_get("usage_json")?,
        verdict_json: row.try_get("verdict_json")?,
        activity_json: row.try_get("activity_json")?,
        object_changed: row.try_get::<i64, _>("object_changed")? != 0,
        modified_source: row.try_get::<i64, _>("modified_source")? != 0,
        created_at: row.try_get("created_at")?,
        finished_at: row.try_get("finished_at")?,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::session_repo::{SessionRecord, SessionRepository};

    async fn db_with_session() -> (Database, SessionId) {
        let db = Database::connect_in_memory().await.unwrap();
        let record = SessionRecord::new("/repo", "goal", "mock/m", leveler_core::now());
        SessionRepository::new(&db).create(&record).await.unwrap();
        (db, SessionId::new(record.id))
    }

    fn new_review<'a>(id: &'a str, session: &'a SessionId) -> NewReview<'a> {
        NewReview {
            id,
            session_id: session,
            focus: "review the change",
            scope_json: r#"{"kind":"workspace"}"#,
            model: "mock/m",
            status: "running",
            source_session_id: Some(session.as_str()),
            source_turn_id: Some("turn-1"),
            created_at: leveler_core::now(),
        }
    }

    #[tokio::test]
    async fn a_review_is_durable_and_settles_once() {
        let (db, session) = db_with_session().await;
        let repo = ReviewRepository::new(&db);
        repo.create(&new_review("review-1", &session))
            .await
            .unwrap();

        let running = repo.get("review-1").await.unwrap().unwrap();
        assert_eq!(running.status, "running");
        assert_eq!(running.findings_json, "[]");
        assert_eq!(running.finished_at, None);

        let finish = ReviewFinish {
            status: "completed",
            object_json: Some(r#"{"head":"abc"}"#),
            findings_json: r#"[{"id":"f-1"}]"#,
            report: "no defects",
            error: None,
            stop_detail: None,
            usage_json: r#"{"input_tokens":10}"#,
            verdict_json: Some(r#"{"conclusion":"no_issues_found"}"#),
            activity_json: r#"[{"tool":"report_review"}]"#,
            object_changed: true,
            modified_source: false,
            finished_at: leveler_core::now(),
        };
        assert!(repo.finish("review-1", &finish).await.unwrap());
        let settled = repo.get("review-1").await.unwrap().unwrap();
        assert_eq!(settled.status, "completed");
        assert_eq!(settled.report, "no defects");
        assert!(settled.object_changed);
        assert!(settled.finished_at.is_some());

        // The first terminal wins: a second settlement must not overwrite it.
        let second = ReviewFinish {
            status: "incomplete",
            object_json: None,
            findings_json: "[]",
            report: "",
            error: None,
            stop_detail: Some("late"),
            usage_json: "{}",
            verdict_json: None,
            activity_json: "[]",
            object_changed: false,
            modified_source: false,
            finished_at: leveler_core::now(),
        };
        assert!(!repo.finish("review-1", &second).await.unwrap());
        let still = repo.get("review-1").await.unwrap().unwrap();
        assert_eq!(still.status, "completed");
        assert_eq!(still.report, "no defects");

        assert!(
            !repo.finish("missing", &finish).await.unwrap(),
            "a finish for an id that was never admitted is not a success"
        );
    }

    /// A review written by the pre-verdict build (schema 0058) must still be
    /// readable after 0059. The absent verdict is "not declared", not a
    /// fabricated clean result.
    #[tokio::test]
    async fn a_review_written_before_the_verdict_column_still_reads() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("sessions.db");
        let mut conn = crate::database::create_legacy_database(&path, 59).await;
        sqlx::query(
            "INSERT INTO sessions (id, repository, goal, status, model, state, created_at, updated_at) \
             VALUES ('s1','/repo','goal','completed','mock/m','complete','t','t')",
        )
        .execute(&mut conn)
        .await
        .unwrap();
        sqlx::query(
            "INSERT INTO reviews \
             (id, session_id, focus, scope_json, model, status, findings_json, report, \
              usage_json, created_at, finished_at) \
             VALUES ('review-old','s1','old focus','{\"kind\":\"workspace\"}','mock/m', \
                     'completed','[]','old report','{}','t','t')",
        )
        .execute(&mut conn)
        .await
        .unwrap();
        use sqlx::Connection;
        conn.close().await.unwrap();

        let db = Database::connect(&path).await.unwrap();
        let record = ReviewRepository::new(&db)
            .get("review-old")
            .await
            .unwrap()
            .expect("the old review survives the migration");
        assert_eq!(record.status, "completed");
        assert_eq!(record.report, "old report");
        assert_eq!(record.verdict_json, None);
    }

    #[tokio::test]
    async fn reviews_are_scoped_to_their_session_newest_first() {
        let (db, session) = db_with_session().await;
        let other = SessionRecord::new("/repo", "goal", "mock/m", leveler_core::now());
        SessionRepository::new(&db).create(&other).await.unwrap();
        let other_session = SessionId::new(other.id);
        let repo = ReviewRepository::new(&db);
        repo.create(&new_review("r-old", &session)).await.unwrap();
        repo.create(&new_review("r-other", &other_session))
            .await
            .unwrap();
        // A later created_at must sort first.
        let mut newer = new_review("r-new", &session);
        newer.created_at = leveler_core::now() + chrono::Duration::seconds(5);
        repo.create(&newer).await.unwrap();

        let rows = repo.list_for_session(&session).await.unwrap();
        let ids: Vec<&str> = rows.iter().map(|row| row.id.as_str()).collect();
        assert_eq!(ids, vec!["r-new", "r-old"]);
    }
}
